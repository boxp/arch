import { readFileSync } from 'node:fs'
import { expect, it } from 'vitest'
import { classifyUpload, PROXY_MAX_BYTES, type UploadFacts } from './attachment-limits.js'

/** BOXP-677: Lean モデル（contract/attachment-model/AttachmentModel.lean）が生成した境界表を実装に照合する。 */
type Case = {
  kind: 'image' | 'pdf' | 'text' | 'unsupported'
  size: number
  opened: 'ok' | 'encrypted' | 'unreadable' | 'timeout'
  pages: number
  textBytes: number
  hasText: boolean
  expected: { proxy?: number; status?: number; error?: string; read?: string }
}
const cases = readFileSync(new URL('../contract/attachment-model/cases.jsonl', import.meta.url), 'utf8')
  .trim()
  .split('\n')
  .map((line) => JSON.parse(line) as Case)

it('has the boundary table generated by the Lean model', () => {
  expect(cases.length).toBeGreaterThan(700)
  for (const kind of ['image', 'pdf', 'text', 'unsupported']) expect(cases.some((c) => c.kind === kind)).toBe(true)
})

it('classifies every boundary case as the model does', () => {
  for (const c of cases) {
    const facts: UploadFacts =
      c.kind === 'pdf'
        ? {
            kind: 'pdf',
            size: c.size,
            pdf:
              c.opened === 'ok'
                ? { status: 'ok', pages: c.pages, textBytes: c.textBytes, hasText: c.hasText }
                : { status: c.opened },
          }
        : c.kind === 'text'
          ? { kind: 'text', size: c.size, textBytes: c.textBytes }
          : { kind: c.kind, size: c.size }
    const got = classifyUpload(facts)
    if (c.expected.proxy) {
      // 中継が断る大きさ。BFF に届いても同じ 413 で断る。
      expect(c.size, JSON.stringify(c)).toBeGreaterThan(PROXY_MAX_BYTES)
      expect(got, JSON.stringify(c)).toMatchObject({ ok: false, status: 413 })
    } else if (c.expected.status === 201)
      expect(got, JSON.stringify(c)).toMatchObject({ ok: true, read: c.expected.read })
    else expect(got, JSON.stringify(c)).toEqual({ ok: false, status: c.expected.status, error: c.expected.error })
  }
})
